const origin = (style: CombatStyle, teacher: string, title: string, body: string, practice: string, accept: string, follow: string, when: Cond[] = []): StyleOrigin =>
  ({ style, teacher, title, body, practice, accept, follow, when });
const weaponOrigin = (style: CombatStyle, teacher: string, mentor: Mentor, when: Cond[],
  story: Pick<StyleOrigin, 'title' | 'body' | 'practice' | 'accept' | 'follow'>): StyleOrigin =>
  ({ style, teacher, mentor, when, ...story });

