export interface StyleOrigin {
  style: CombatStyle; teacher: string; title: string; body: string; practice: string; accept: string; follow: string;
  when: Cond[];
  mentor?: Mentor;
}
const island = (...is: string[]): Cond => ({ c: 'island', is });
